import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { writeFile } from 'node:fs/promises';
import { join } from 'node:path';

export async function checkReplayReader(page, runtime, output) {
  const root=join(runtime.home,'projects','harmony');
  const git=(...args)=>execFileSync('git',['-c','user.name=Journal Fixture','-c','user.email=journal@example.invalid',...args],{cwd:root,encoding:'utf8'}).trim();
  git('init','-q');
  await writeFile(join(root,'route.js'),'export const route = "start";\n');
  await writeFile(join(root,'AGENTS.md'),'保留已有项目命名。\n');
  git('add','route.js','AGENTS.md');git('commit','-qm','开工之前');
  const base=git('rev-parse','HEAD');
  await writeFile(join(root,'route.js'),'export const route = "reference";\n');
  await writeFile(join(root,'reference-only.js'),'export const historicalAnswer = "private";\n');
  git('add','route.js','reference-only.js');git('commit','-qm','验收交付');
  const reference=git('rev-parse','HEAD');
  const calls=() => runtime.api('status',{},'journal-test').then(value=>value.calls);
  const button=name=>page.getByRole('button',{name,exact:true});
  const panel=page.getByRole('region',{name:'工作区复演',exact:true});
  const toggle=page.getByRole('button',{name:/已收藏 · 工作区复演/});
  // The host persists immediately but the reply may arrive after switching readers.
  let release, reached;
  const delayed = new Promise(resolve=>{release=resolve;});
  const persisted = new Promise(resolve=>{reached=resolve;});
  const holdFavorite = async route => {
    if (route.request().postDataJSON()?.action !== 'replayFavorite') return route.continue();
    const response = await route.fetch();
    reached();
    await delayed;
    await route.fulfill({response}).catch(()=>{});
  };
  const endpoint='**/api/dsh-collab-journal';
  await page.route(endpoint,holdFavorite);
  await button('收藏会话').click();
  await persisted;
  await page.locator('.cj-workspaces button[title$="android"]').click();
  await page.getByRole('heading',{name:'检查 Android Push API',exact:true}).waitFor();
  release();
  await page.unroute(endpoint,holdFavorite);
  await button('收藏会话').waitFor();
  await page.locator('.cj-workspaces button[title$="harmony"]').click();
  await page.getByRole('heading',{name:'统一流量购买 H5 跳转',exact:true}).waitFor();
  await toggle.waitFor({timeout:4000});
  await button('我的收藏').click();
  await page.getByRole('heading',{name:'统一流量购买 H5 跳转',exact:true}).waitFor();
  assert.equal(await page.locator('.cj-session').count(),1);
  await toggle.click();await button('准备复演').click();
  const save=button('保存复演材料');
  assert.equal(await save.isDisabled(),true);
  await panel.getByLabel('开工时的代码的提交列表').selectOption(base);
  await panel.getByLabel('我认可的交付的提交列表').selectOption(reference);
  await panel.getByRole('checkbox',{name:'route.js',exact:true}).check();
  assert.equal(await panel.getByRole('checkbox',{name:'reference-only.js',exact:true}).count(),0,'the reference must not reveal paths introduced by the historical solution');
  await panel.getByText(/选择后来新增的要求/).click();
  assert.equal(await panel.getByRole('checkbox',{name:/不是只改安卓/}).isChecked(),false);
  await save.click();
  await button('试一条工作区规则').waitFor();
  await panel.getByText('已选复演材料 · 1 个文件',{exact:true}).click();
  await panel.getByText('开工时的 AGENTS.md',{exact:true}).click();
  await panel.getByText('保留已有项目命名。',{exact:true}).waitFor();
  assert.equal(await calls(),0,'browsing, saving and choosing inputs must not call the model');
  await button('试一条工作区规则').click();
  const result=panel.getByRole('region',{name:'复演交付对照'});
  await result.waitFor();
  assert.equal(await calls(),4,'research, isolated rule writing, baseline and candidate must each run once');
  const original=result.getByRole('region',{name:'原认可交付'});
  const candidate=result.getByRole('region',{name:'新规则交付'});
  assert.match(await original.innerText(),/export const route = "reference"/);
  assert.match(await candidate.innerText(),/export const route = "candidate"/);
  await result.getByText('查看同一起点用旧规则重做的文件',{exact:true}).click();
  await result.getByText('export const route = "baseline";',{exact:true}).waitFor();
  assert.equal(await button('保存我的判断').isDisabled(),true,'a completed replay must not imply a human preference');
  await result.getByRole('radio',{name:'更喜欢原版'}).check();
  await result.getByRole('textbox',{name:'评语（选填）'}).fill('合成用例评审');
  await button('保存我的判断').click();
  await result.getByText('已保存 · 更喜欢原版',{exact:true}).waitFor();
  await page.screenshot({path:join(output,'dsh-journal-replay.png'),fullPage:true});
  await page.setViewportSize({width:560,height:900});
  assert.ok(await panel.evaluate(element=>element.scrollWidth<=element.clientWidth+1),'file comparison must fit the host at narrow widths');
  await page.screenshot({path:join(output,'dsh-journal-replay-narrow.png'),fullPage:true});
  await page.setViewportSize({width:1500,height:1050});
  await runtime.api('fail',{value:true},'journal-test');
  await button('再次试一条规则').click();
  await panel.getByText('复演未完成',{exact:true}).waitFor();
  await result.getByText('上次完成的文件对照',{exact:true}).waitFor();
  assert.match(await original.innerText(),/reference/);
  await runtime.api('fail',{value:false},'journal-test');
  await button('取消收藏').click();
  await page.getByText('这个范围内还没有收藏的会话',{exact:true}).waitFor();
  await button('按日期').click();
  await button('收藏会话').click();await toggle.click();
  await result.getByText('已保存 · 更喜欢原版',{exact:true}).waitFor();
  await toggle.click();
  return calls();
}
